function normalizeQuoteText(string $quote): string
{
    // Keep original wording but normalize surrounding whitespace for consistent rendering.
    return trim(preg_replace('/\R{3,}/', "\n\n", $quote));
}

function buildQuoteCatalog(array $quotes, string $source): array
{
    $catalog = [];
    foreach ($quotes as $quote) {
        $catalog[] = [
            'text' => normalizeQuoteText($quote),
            'source' => $source,
        ];
    }

    return $catalog;
}

